"""Old ieef.or.id (Hostinger) addresses -> new pages. Writes worker/redirects.js. Run: python3 migration/make_redirects.py"""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
news = json.loads((ROOT / 'src/data/snapshot/news.json').read_text())
people = json.loads((ROOT / 'src/data/snapshot/people.json').read_text())
R = {}
for n in news:
    if n.get('legacy_slug'): R['/' + n['legacy_slug']] = '/news/' + n['slug']
for p in people: R['/' + p['slug']] = '/team/' + p['slug']
for old, new in {'post-doctoral': 'post-doctoral', 'research-associate': 'research-associate',
                 'internship-program': 'internship-program', 'research-asisstant': 'research-assistant'}.items():
    R['/' + old] = '/career/' + new
for k in ['news-and-article-1', 'news-and-article-2']: R['/' + k] = '/news-and-article'
for k in ['page-2-research-2018-2022', 'page-3-research-2025', 'page-4-research-2025-2-copy', 'page-5-research-2026-2025']:
    R['/' + k] = '/research-publication'
R['/ieef-and-sbm-itb-strengthen-financial-literacy-in-mertak-village-central-lombok'] = '/news/financial-literacy-mertak-village-lombok'
R['/driving-sustainable-development-in-indonesias-economic-and-financial-sectors'] = '/about-us'
R['/driving-sustainable-development-in-indonesias-economic-landscape'] = '/about-us'
R.update({'/home': '/', '/careers': '/career', '/contact': '/contact-us', '/news': '/news-and-article', '/about': '/about-us', '/team': '/about-us#team'})
(ROOT / 'worker/redirects.js').write_text(
    '// Old ieef.or.id addresses (Hostinger site) -> new pages. Generated by migration/make_redirects.py\nexport const REDIRECTS = '
    + json.dumps(R, indent=1) + ';\n')
print(len(R), 'redirects')
