"""Build supabase/seed.sql from migration/content/*.json (one-time import of the old site's content).

Run:  python3 migration/make_seed.py
"""
import json, re
from pathlib import Path

HERE = Path(__file__).parent
C = HERE / 'content'
OUT = HERE.parent / 'supabase' / 'seed.sql'

def q(v):
    if v is None: return 'null'
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, int): return str(v)
    if isinstance(v, list): return "array[" + ", ".join(q(x) for x in v) + "]::text[]" if v else "'{}'::text[]"
    return "'" + str(v).replace("'", "''") + "'"

def slugify(s, n=70):
    s = re.sub(r'[’\'"]', '', s.lower())
    s = re.sub(r'[^a-z0-9]+', '-', s).strip('-')
    return s[:n].rstrip('-')

SNAP = HERE.parent / 'src' / 'data' / 'snapshot'
SNAP.mkdir(parents=True, exist_ok=True)

def insert(table, rows):
    (SNAP / f'{table}.json').write_text(json.dumps(rows, ensure_ascii=False, indent=1))
    cols = list(rows[0].keys())
    vals = ',\n'.join('  (' + ', '.join(q(r[c]) for c in cols) + ')' for r in rows)
    return f'insert into public.{table} ({", ".join(chr(34) + c + chr(34) if c == "group" else c for c in cols)}) values\n{vals};\n'

sql = ['-- One-time import of content from the old ieef.or.id (generated by migration/make_seed.py).',
       '-- English is the original language except careers, which were published in Bahasa Indonesia.',
       'begin;']

ROLES_ID = {
    'ir-dzikri-firmansyah-hakam-st-pgdip-msc-phd-cfpr': 'Direktur Eksekutif, IEEF',
    'yudo-anggoro-stmsmphd': 'Direktur, Center for Policy and Public Management, SBM ITB',
    'dr-erman-a-sumirat-se-mbuss-csa-crp-cibcwm-ak': 'Keuangan strategis, investasi, dan manajemen risiko',
    'atika-irawan-smn-msc-phd-cand': 'Dosen SBM ITB: keuangan dan keuangan syariah',
    'achmad-billy-zulqiyami-st-sh-mh-phd-cand': 'Hukum bisnis, regulasi, dan kajian kebijakan',
    'alif-hijriah-ssi-msi': 'Analisis dan pemodelan ekonomi kuantitatif',
    'nitha-pricillia-se-mm-phd-cand': 'Program Director, CRMS Indonesia',
    'khairil-insan-bintang-spd-mpd': 'Peneliti, IEEF',
    'sophia-roosma-hardeny-st-mba': 'Manajemen konstruksi dan risiko proyek',
    'anisya-nurfitri-k-spd-msm': 'Manajer Proyek dan Asisten Peneliti, IEEF',
    'fadhil-nurilman-muhammad-sm-mba': 'Kajian dampak ekonomi dan studi kelayakan',
    'ihda-farhatun-nisak-spd-mm': 'Peneliti, IEEF',
}
people = json.loads((C / 'people.json').read_text())
sql.append(insert('people', [{
    'slug': p['slug'], 'name': p['name'], 'group': p['group'], 'role_en': p['role'], 'role_id': ROLES_ID.get(p['slug']),
    'bio_en': '\n\n'.join(p['bio']), 'bio_id': None, 'photo': 'repo:' + p['photo_local'],
    'social_url': p['social'], 'sort': p['sort'], 'published': True} for p in people]))

THEMES = {1: 'energy', 2: 'social', 3: 'economy', 4: 'economy', 5: 'energy', 6: 'economy', 7: 'energy', 8: 'energy', 9: 'energy', 10: 'energy'}
briefs = json.loads((C / 'policy-briefs.json').read_text())
rows = []
for b in briefs:
    title = b.get('title_full') or b['title']
    slug = {3: 'when-growth-is-not-enough', 10: 'mega-conversion-lpg-to-induction-stove'}.get(b['sort']) or slugify(title.split(':')[0] if len(title) > 80 else title)
    rows.append({'kind': 'policy_brief', 'slug': slug, 'title': title,
                 'summary_en': None, 'summary_id': None,
                 'year': int(b['published'][:4]) if b.get('published') else None, 'published_on': b.get('published'),
                 'theme': THEMES[b['sort']], 'pdf_url': b['pdf_url'], 'journal_url': b['journal_url'], 'cover': None,
                 'featured': b['sort'] == 1, 'sort': b['sort'], 'published': True})
research = json.loads((C / 'research.json').read_text())
seen = {r['slug'] for r in rows}
for i, r in enumerate(research):
    s = slugify(r['title'])
    while s in seen: s += '-r'
    seen.add(s)
    rows.append({'kind': 'research', 'slug': s, 'title': r['title'], 'summary_en': None, 'summary_id': None,
                 'year': r['year'], 'published_on': None, 'theme': None, 'pdf_url': None, 'journal_url': r['url'], 'cover': None,
                 'featured': bool(r.get('featured')), 'sort': i + 1, 'published': True})
sql.append(insert('publications', rows))

news = json.loads((C / 'news.json').read_text())
sql.append(insert('news', [{
    'slug': n['slug'], 'date': n['date'], 'place': n['place'], 'title_en': n['title'], 'title_id': None,
    'tagline_en': n['tagline'], 'tagline_id': None, 'summary_en': n['summary'], 'summary_id': None,
    'body_en': '\n\n'.join(n['body']), 'body_id': None, 'image': 'repo:' + n['image_local'],
    'source_label': (n['source'] or {}).get('label'), 'source_url': (n['source'] or {}).get('url'), 'published': True} for n in news]))

careers = json.loads((C / 'careers.json').read_text())
sql.append(insert('careers', [{
    'slug': 'research-assistant' if c['slug'] == 'research-asisstant' else c['slug'],
    'title_en': None, 'title_id': c['title'], 'intro_en': None, 'intro_id': c['intro'],
    'qualifications_en': [], 'qualifications_id': c['qualifications'],
    'responsibilities_en': [], 'responsibilities_id': c['responsibilities'],
    'notes_en': [], 'notes_id': c['notes'], 'apply_url': c['apply_url'], 'poster': 'repo:' + c['poster_local'],
    'is_open': True, 'sort': c['sort'], 'published': True} for c in careers]))

partners = json.loads((C / 'partners.json').read_text())
sql.append(insert('partners', [{'name': p['name'], 'logo': 'repo:' + p['logo_local'], 'website_url': None, 'sort': p['sort'], 'published': True}
                               for p in partners]))
sql.append('commit;')
OUT.write_text('\n'.join(sql) + '\n')
print(f'wrote {OUT} ({OUT.stat().st_size // 1024} KB): {len(people)} people, {len(rows)} publications, {len(news)} news, {len(careers)} careers, {len(partners)} partners')
